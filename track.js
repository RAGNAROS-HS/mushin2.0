/* The woods: draw track icons, ring strips and objective saplings, and
   handle the three linkable filters. Pages are generated by bin/build.py;
   this only adds behaviour. Filters live in the URL so a view can be linked:
     #obj=<id>     track page: entries that practise or pass an objective
     #track=<slug> woods hub: entries of one track
     #book=<id>    shelf: one book, its details and where it's cited */
(function () {
  "use strict";

  var P = window.HSKPixel;
  var each = function (sel, fn) { Array.prototype.forEach.call(document.querySelectorAll(sel), fn); };

  /* ------------------------------------------------------------- sprites */

  if (P) {
    each("[data-ticon]", function (el) { el.innerHTML = P.icon(el.getAttribute("data-ticon")); });
    each("[data-ring]", function (el) { el.innerHTML = P.ring(el.getAttribute("data-ring")); });
    each("[data-glyph]", function (el) {
      var svg = P.sprite(el.getAttribute("data-glyph"));
      if (svg) { el.insertAdjacentHTML("afterbegin", svg); el.classList.add("has-px"); }
    });
  }

  /* One sapling per objective, in the track's species, felled once passed. */
  var buttons = document.querySelectorAll(".obj");
  var groves = document.querySelector(".groves");
  if (P && P.grove && groves) {
    var species = groves.getAttribute("data-species");
    Array.prototype.forEach.call(buttons, function (b) {
      b.insertAdjacentHTML("afterbegin", P.grove(b.getAttribute("data-state"), b.getAttribute("data-obj"), species));
      b.classList.add("has-px");
    });
  }

  /* ------------------------------------------------------------- filters */

  function param(name) {
    var m = new RegExp("(?:^|[#&])" + name + "=([a-z0-9]+(?:-[a-z0-9]+)*)").exec(window.location.hash);
    return m ? m[1] : null;
  }

  function clearHash() {
    history.replaceState(null, "", window.location.pathname);
    apply();
  }

  var rows = document.querySelectorAll(".wu");
  var empty = document.getElementById("wu-empty");
  var detail = document.getElementById("obj-detail");
  var detailText = document.getElementById("obj-detail-text");

  function filterRows(match) {
    var shown = 0;
    Array.prototype.forEach.call(rows, function (r) {
      r.hidden = !match(r);
      if (!r.hidden) shown++;
    });
    /* a month heading only shows if one of its entries does */
    each(".month", function (m) { m.hidden = !m.querySelector(".wu:not([hidden])"); });
    if (empty) empty.hidden = rows.length > 0 ? shown > 0 : false;
  }

  function apply() {
    /* objective (track page) */
    var obj = param("obj"), btn = null;
    Array.prototype.forEach.call(buttons, function (b) {
      var on = b.getAttribute("data-obj") === obj;
      b.setAttribute("aria-pressed", on ? "true" : "false");
      if (on) btn = b;
    });
    if (!btn) obj = null;
    if (detail) {
      detail.hidden = !btn;
      if (btn) {
        /* open right under the clicked tree's grove, where the eye already is */
        var trees = btn.closest(".grove-trees");
        if (trees && trees.nextElementSibling !== detail) trees.insertAdjacentElement("afterend", detail);
        detailText.textContent = obj + " · " + btn.getAttribute("data-text") + " — " + btn.getAttribute("data-state");
      }
    }

    /* track (woods hub) */
    var track = param("track");
    each(".chip", function (c) {
      var on = (c.getAttribute("data-track") || null) === track;
      if (on) c.setAttribute("aria-current", "true"); else c.removeAttribute("aria-current");
    });

    filterRows(function (r) {
      if (obj && (" " + r.getAttribute("data-objs") + " ").indexOf(" " + obj + " ") < 0) return false;
      if (track && r.getAttribute("data-track") !== track) return false;
      return true;
    });

    /* book (shelf) */
    var book = param("book"), li = book && document.getElementById("book-" + book);
    var bookDetail = document.getElementById("book-detail");
    each(".book", function (b) { b.classList.toggle("is-on", b === li); });
    each(".spine", function (s) { s.classList.toggle("is-on", li && s.getAttribute("data-book") === book); });
    if (bookDetail) {
      bookDetail.hidden = !li;
      if (li) document.getElementById("book-detail-text").innerHTML = li.innerHTML;
    }
  }

  Array.prototype.forEach.call(buttons, function (b) {
    b.addEventListener("click", function () {
      var id = b.getAttribute("data-obj");
      if (param("obj") === id) clearHash();
      else window.location.hash = "obj=" + id;
      if (P && P.chew) P.chew();
    });
  });
  each(".chip", function (c) {
    if (!c.getAttribute("data-track")) {
      c.addEventListener("click", function (ev) { ev.preventDefault(); clearHash(); });
    }
  });
  ["obj-clear", "book-clear"].forEach(function (id) {
    var el = document.getElementById(id);
    if (el) el.addEventListener("click", clearHash);
  });

  window.addEventListener("hashchange", apply);
  apply();
})();
